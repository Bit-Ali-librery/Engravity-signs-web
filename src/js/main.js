// === OS Detection Logic ===
window.detectOS = () => {
  const userAgent = window.navigator.userAgent.toLowerCase();
  const lang = window.currentLang || 'es';
  const labels = {
    es: { download: "Descargar", forOS: "Descargar para" },
    en: { download: "Download", forOS: "Download for" },
    fr: { download: "Télécharger", forOS: "Télécharger pour" }
  };
  const t = labels[lang] || labels.es;
  let os = "Unknown OS";
  let osIcon = "💻";
  let downloadText = t.download;
  let fileSizeInfo = "";

  if (userAgent.indexOf("win") !== -1) {
    os = "Windows";
    osIcon = "🪟";
    downloadText = `${t.forOS} Windows`;
    fileSizeInfo = "Windows 10/11 — 85 MB";
  } else if (userAgent.indexOf("mac") !== -1) {
    os = "macOS";
    osIcon = "🍎";
    downloadText = `${t.forOS} macOS`;
    fileSizeInfo = "Apple Silicon / Intel — 92 MB";
  } else if (userAgent.indexOf("linux") !== -1) {
    os = "Linux";
    osIcon = "🐧";
    downloadText = `${t.forOS} Linux`;
    fileSizeInfo = "AppImage — 78 MB";
  }

  // Update elements
  const osNameEls = document.querySelectorAll('.detected-os-name');
  osNameEls.forEach(el => el.innerText = os);

  const fileSizeEls = document.querySelectorAll('.detected-os-size');
  fileSizeEls.forEach(el => el.innerText = fileSizeInfo);

  const mainDownloadBtns = document.querySelectorAll('.dynamic-os-download');
  mainDownloadBtns.forEach(btn => {
    btn.innerHTML = `${osIcon}&nbsp;&nbsp;${downloadText}`;
  });

  return os;
};
