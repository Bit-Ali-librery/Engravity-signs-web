window.currentLang = 'en';
window.changeLanguage = (lang) => {
  const dict = translations[lang];
  if (!dict) return;
  window.currentLang = lang;
  try { localStorage.setItem('engravity.lang', lang); } catch (_) { /* localStorage may be blocked */ }

  // Change Button Text
  const btnText = lang === 'es' ? 'ES ▾' : lang === 'en' ? 'EN ▾' : 'FR ▾';
  const toggleBtn = document.getElementById('langToggle');
  if (toggleBtn) toggleBtn.innerText = btnText;

  // innerHTML translations
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.innerHTML = dict[key];
  });

  // Title attribute translations
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (dict[key]) el.setAttribute('title', dict[key]);
  });

  // Placeholder attribute translations
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) el.setAttribute('placeholder', dict[key]);
  });

  document.documentElement.lang = lang;

  // Translate page title + meta description
  if (dict["page.title"]) document.title = dict["page.title"];
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && dict["page.description"]) metaDesc.setAttribute('content', dict["page.description"]);

  // Re-run OS detection so the dynamic Download button picks the new language
  if (typeof window.detectOS === 'function') window.detectOS();
};

